const cache = new Map<BenAlien, HTMLCanvasElement>();
const illustratedForms = new Set<BenAlien>(["diamondhead", "feedback", "humungousaur", "bigChill", "ghostfreak", "nrg"]);
const illustratedPortraits = new Map<BenAlien, HTMLImageElement>();

export function alienPortrait(id: BenAlien) {
  if (illustratedForms.has(id)) {
    let portrait = illustratedPortraits.get(id);
    if (!portrait) {
      portrait = new Image();
      portrait.src = `${assetBase}sprites/ben/${id}/portrait.png`;
      illustratedPortraits.set(id, portrait);
    }
    if (portrait.complete && portrait.naturalWidth) return portrait;
  }
  const cached = cache.get(id);
  if (cached) return cached;
  const canvas = document.createElement("canvas");
  canvas.width = canvas.height = 48;
  const ctx = canvas.getContext("2d")!;
  for (const [color, points] of portraits[id]) {
    // Scan-convert each polygon into runs of whole pixels.
    const vertices = points.split(" ").map(pair => pair.split(",").map(Number));
    ctx.fillStyle = color;
    for (let y = 0; y < canvas.height; y++) {
      const scanY = y + .5;
      const hits: number[] = [];
      for (let i = 0; i < vertices.length; i++) {
        const [x0, y0] = vertices[i];
        const [x1, y1] = vertices[(i + 1) % vertices.length];
        if ((y0 > scanY) !== (y1 > scanY))
          hits.push(x0 + (scanY - y0) * (x1 - x0) / (y1 - y0));
      }
      hits.sort((a, b) => a - b);
      for (let i = 0; i + 1 < hits.length; i += 2) {
        const start = Math.ceil(hits[i] - .5);
        const end = Math.ceil(hits[i + 1] - .5);
        ctx.fillRect(start, y, end - start, 1);
      }
    }
  }
  cache.set(id, canvas);
  return canvas;
}

